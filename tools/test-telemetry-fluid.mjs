/* Offline telemetry scheduling, delta-fetch and real-sample playback checks. */
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {runInNewContext} from 'node:vm';
const source=readFileSync('telemetry-cloud.js','utf8');
const rows=Array.from({length:40},(_,i)=>({lap_number:i+1,samples:[{world_x:i,world_z:0}]}));
let calls=0;
const env={Map,Set,Math,Number,api:async(action,args)=>{calls++;return {laps:Array.from({length:8},(_,i)=>({lap_number:42-i,samples:[{world_x:42-i,world_z:0}]}))}}};
runInNewContext(source.slice(source.indexOf('async function fetchSessionLaps('),source.indexOf('async function refreshData(')),env);
const result=await env.fetchSessionLaps('session',40,rows);
assert.equal(calls,1,'Only new page fetched when previous laps overlap');
assert.equal(result.length,40);assert.equal(result.at(-1).lap_number,42);
assert.equal(result[0].lap_number,3);assert.equal(rows.length,40);
const app={active:true,failures:0};let delay,callback,refreshes=0;
const scheduler={app,REFRESH_MS:120000,ACTIVE_REFRESH_MS:5000,clearTimeout:()=>{},setTimeout:(fn,ms)=>{callback=fn;delay=ms},document:{hidden:false},refreshData:()=>refreshes++};
runInNewContext(source.slice(source.indexOf('function scheduleRefresh(){'),source.indexOf('function start(){')),scheduler);
scheduler.scheduleRefresh();assert.equal(delay,5000);
callback();assert.equal(refreshes,1);
app.failures=1;scheduler.scheduleRefresh();assert.equal(delay,10000);
app.failures=5;scheduler.scheduleRefresh();assert.equal(delay,120000);
app.failures=0;app.active=false;scheduler.scheduleRefresh();assert.equal(delay,120000);
scheduler.document.hidden=true;callback();assert.equal(refreshes,1,'Hidden tab does not query');
const live=readFileSync('telemetry-live.js','utf8');
const buffer=[{t:1,world_x:0,brake:0},{t:1.1,world_x:2,brake:.5},{t:1.2,world_x:3,brake:1}];
const playback={state:{buffer,lastFrame:1000},Date,Math};
runInNewContext(live.slice(live.indexOf('function displaySample('),live.indexOf('function mainPlot(){')),playback);
assert.equal(playback.displaySample(1000),buffer[0]);
assert.equal(playback.displaySample(1110),buffer[1]);
assert.equal(playback.displaySample(5000),buffer[2],'Do not extrapolate through outage');
playback.state.buffer=[];assert.equal(playback.displaySample(),null);
assert.match(live,/if\(p.session_id&&state.session!==p.session_id\)return/,'Reject frames from other session');
assert.match(source,/if\(app.busy\)\{app.manualPending \|\|= forced;return\}/,'Manual refresh queues without overlap');
console.log('Telemetry delta fetch, 5s/120s scheduler/backoff and timestamped playback passed');
